//! Tauri integration, compiled only with the `tauri` feature.
//!
//! Apps list the commands in [`commands`] by full path in their own
//! `generate_handler!`, and list the bare names in [`COMMAND_NAMES`] in their
//! `build.rs` `AppManifest` and capability file (verified in S02 task 1.1).
//! Every input is validated here before use.

use crate::session::{ConnState, SessionEvents};
use crate::{KeychainVault, ServerService, SshConnector, Store};
use ossiframe_core::Registry;
use serde::Serialize;
use std::sync::Arc;
use tauri::{AppHandle, Emitter, Manager, Runtime};

/// Bare names of the shared commands, for `AppManifest::commands` and
/// capability `allow-` entries (kebab-case).
pub const COMMAND_NAMES: &[&str] = &[
    "list_servers",
    "add_server",
    "update_server",
    "remove_server",
    "connect_server",
    "disconnect_server",
    "trust_host_key",
    "replace_host_key",
    "cancel_operation",
    "run_operation",
    "list_modules",
];

/// Per-app settings for [`setup`].
pub struct AppSetup<'a> {
    /// File name (no directory) of the SQLite database in the app data
    /// directory, for example `app.sqlite3`.
    pub db_file: &'a str,
    /// Modules compiled into the app. Build it with `Registry::builder()`;
    /// a failed build should stop the app at startup with the error text,
    /// for example `.build().expect("module registry")`.
    pub registry: Registry,
}

/// Opens the local store in the app data directory, uses the app identifier
/// from `tauri.conf.json` as the keychain service name, and manages the
/// [`ServerService`] and `Arc<Registry>` as Tauri state. Because both the
/// data directory and the keychain service derive from the identifier, two
/// apps with different identifiers never share data or secrets.
pub fn setup<R: Runtime>(
    app: &mut tauri::App<R>,
    cfg: AppSetup<'_>,
) -> Result<(), Box<dyn std::error::Error>> {
    if !valid_db_file(cfg.db_file) {
        return Err(format!("invalid database file name '{}'", cfg.db_file).into());
    }
    let dir = app.path().app_data_dir()?;
    std::fs::create_dir_all(&dir)?;
    let store = Store::open(&dir.join(cfg.db_file))
        .map_err(|e| format!("cannot open local database: {e}"))?;
    let identifier = app.config().identifier.clone();
    let service = ServerService::new(
        store,
        Arc::new(KeychainVault::new(&identifier)),
        Arc::new(SshConnector::default()),
        Arc::new(TauriEvents(app.handle().clone())),
    );
    app.manage(service);
    app.manage(Arc::new(cfg.registry));
    Ok(())
}

/// A plain file name: no separators, no `..`, not empty.
fn valid_db_file(name: &str) -> bool {
    !name.is_empty()
        && name != "."
        && name != ".."
        && name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'.' | b'_' | b'-'))
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct StatePayload<'a> {
    server_id: &'a str,
    state: ConnState,
}

#[derive(Clone, Serialize)]
#[serde(rename_all = "camelCase")]
struct LostPayload<'a> {
    server_id: &'a str,
}

/// Emits connection events to the frontend.
pub struct TauriEvents<R: Runtime>(pub AppHandle<R>);

impl<R: Runtime> SessionEvents for TauriEvents<R> {
    fn state_changed(&self, server_id: &str, state: ConnState) {
        let _ = self
            .0
            .emit("connection-state", StatePayload { server_id, state });
    }
    fn connection_lost(&self, server_id: &str) {
        let _ = self.0.emit("connection-lost", LostPayload { server_id });
    }
}

pub mod commands {
    use crate::ServerService;
    use crate::dispatch::ModuleDto;
    use crate::ipc::{ConnectOutcomeDto, IpcError, ProfileInputDto, ServerDto};
    use ossiframe_core::{Registry, SecretString};
    use std::sync::Arc;
    use tauri::State;

    type Svc<'a> = State<'a, ServerService>;

    /// True for the canonical UUID text form `8-4-4-4-12` (hex digits).
    fn is_uuid(s: &str) -> bool {
        let groups: Vec<&str> = s.split('-').collect();
        groups.len() == 5
            && groups
                .iter()
                .zip([8, 4, 4, 4, 12])
                .all(|(g, n)| g.len() == n && g.bytes().all(|b| b.is_ascii_hexdigit()))
    }

    /// Server IDs are UUIDs generated by the backend.
    pub fn server_id(id: &str) -> Result<&str, IpcError> {
        if is_uuid(id) {
            Ok(id)
        } else {
            Err(IpcError::NotFound)
        }
    }

    fn token(t: &str) -> Result<&str, IpcError> {
        if is_uuid(t) {
            Ok(t)
        } else {
            Err(IpcError::HostKeyApproval {
                message: "host key approval is unknown or was already used".into(),
            })
        }
    }

    #[tauri::command]
    pub async fn list_servers(svc: Svc<'_>) -> Result<Vec<ServerDto>, IpcError> {
        Ok(svc.list()?.into_iter().map(Into::into).collect())
    }

    #[tauri::command]
    pub async fn add_server(svc: Svc<'_>, input: ProfileInputDto) -> Result<ServerDto, IpcError> {
        Ok(svc.add(input.validate()?)?.into())
    }

    #[tauri::command]
    pub async fn update_server(
        svc: Svc<'_>,
        server_id: String,
        input: ProfileInputDto,
    ) -> Result<ServerDto, IpcError> {
        let id = self::server_id(&server_id)?;
        Ok(svc.update(id, input.validate()?).await?.into())
    }

    #[tauri::command]
    pub async fn remove_server(svc: Svc<'_>, server_id: String) -> Result<(), IpcError> {
        Ok(svc.remove(self::server_id(&server_id)?).await?)
    }

    /// `credential` is a password or key passphrase for this attempt only.
    #[tauri::command]
    pub async fn connect_server(
        svc: Svc<'_>,
        server_id: String,
        credential: Option<SecretString>,
        save_secret: bool,
    ) -> Result<ConnectOutcomeDto, IpcError> {
        let id = self::server_id(&server_id)?;
        Ok(svc.connect(id, credential, save_secret).await?.into())
    }

    #[tauri::command]
    pub async fn disconnect_server(svc: Svc<'_>, server_id: String) -> Result<(), IpcError> {
        Ok(svc.disconnect(self::server_id(&server_id)?).await?)
    }

    #[tauri::command]
    pub async fn trust_host_key(
        svc: Svc<'_>,
        server_id: String,
        token: String,
    ) -> Result<(), IpcError> {
        Ok(svc
            .trust_host_key(self::server_id(&server_id)?, self::token(&token)?)
            .await?)
    }

    #[tauri::command]
    pub async fn replace_host_key(
        svc: Svc<'_>,
        server_id: String,
        token: String,
        confirm_host: String,
    ) -> Result<(), IpcError> {
        if confirm_host.len() > 253 {
            return Err(IpcError::ConfirmationMismatch);
        }
        Ok(svc
            .replace_host_key(
                self::server_id(&server_id)?,
                self::token(&token)?,
                &confirm_host,
            )
            .await?)
    }

    #[tauri::command]
    pub async fn cancel_operation(svc: Svc<'_>, server_id: String) -> Result<(), IpcError> {
        svc.cancel_operation(self::server_id(&server_id)?);
        Ok(())
    }

    /// Runs one operation of a module compiled into the app. `args` is
    /// opaque JSON validated by the module.
    #[tauri::command]
    pub async fn run_operation(
        svc: Svc<'_>,
        registry: State<'_, Arc<Registry>>,
        server_id: String,
        module_id: String,
        operation_id: String,
        args: Option<serde_json::Value>,
    ) -> Result<serde_json::Value, IpcError> {
        crate::dispatch::run_operation(
            &svc,
            &registry,
            &server_id,
            &module_id,
            &operation_id,
            args.unwrap_or(serde_json::Value::Null),
        )
        .await
    }

    /// Registered modules and their operations.
    #[tauri::command]
    pub async fn list_modules(
        registry: State<'_, Arc<Registry>>,
    ) -> Result<Vec<ModuleDto>, IpcError> {
        Ok(crate::dispatch::list_modules(&registry))
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn db_file_must_be_a_plain_name() {
            assert!(super::super::valid_db_file("doctor.sqlite3"));
            for bad in ["", "..", "a/b", "../x", "a\\b", "x y"] {
                assert!(!super::super::valid_db_file(bad), "{bad}");
            }
        }

        #[test]
        fn command_names_are_unique_and_include_new_commands() {
            let set: std::collections::BTreeSet<_> = super::super::COMMAND_NAMES.iter().collect();
            assert_eq!(set.len(), super::super::COMMAND_NAMES.len());
            assert!(set.contains(&"run_operation") && set.contains(&"list_modules"));
        }

        #[test]
        fn ids_and_tokens_are_validated() {
            assert!(server_id("3f2a7b1c-0000-4000-8000-000000000000").is_ok());
            for bad in [
                "",
                "../../etc/passwd",
                "1; DROP TABLE servers",
                &"a".repeat(36),
                "3f2a7b1c-0000-4000-8000-00000000000Z",
            ] {
                assert!(server_id(bad).is_err(), "{bad}");
            }
            assert!(token("x").is_err());
        }
    }
}
